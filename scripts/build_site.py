#!/usr/bin/env python3
"""Build site/data.js from context/ so site/index.html can show it.

Usage: python3 scripts/build_site.py
Reads context/vacancies/*.md, context/interview-prep/*.md, context/sync-log.md.
Uses only the standard library.
"""
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTEXT = ROOT / "context"
OUT = ROOT / "site" / "data.js"


def parse_note(text):
    """Split a '---' front matter block of 'key: value' lines from the body."""
    meta, body = {}, text
    if text.startswith("---"):
        parts = text.split("---", 2)
        if len(parts) == 3:
            for line in parts[1].splitlines():
                if ":" in line:
                    key, value = line.split(":", 1)
                    meta[key.strip()] = value.strip()
            body = parts[2]
    return meta, body.strip()


def read_vacancies():
    items = []
    for path in sorted((CONTEXT / "vacancies").glob("*.md")):
        meta, body = parse_note(path.read_text(encoding="utf-8"))
        meta["file"] = path.relative_to(ROOT).as_posix()
        meta["summary"] = body
        items.append(meta)
    return items


def read_prep():
    return [
        {"file": p.relative_to(ROOT).as_posix(), "text": p.read_text(encoding="utf-8")}
        for p in sorted((CONTEXT / "interview-prep").glob("*.md"))
    ]


def main():
    log = CONTEXT / "sync-log.md"
    data = {
        "built": date.today().isoformat(),
        "vacancies": read_vacancies(),
        "prep": read_prep(),
        "syncLog": log.read_text(encoding="utf-8") if log.exists() else "",
    }
    OUT.write_text(
        "// Generated by scripts/build_site.py. Do not edit.\n"
        "window.HARNESS_DATA = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(data['vacancies'])} vacancies, {len(data['prep'])} prep notes")


if __name__ == "__main__":
    sys.exit(main())
